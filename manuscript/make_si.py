import si_tables_v2 as V
RES = '/home/claude/hea/results'
REPRO = {'xgb': '0 HV or MPa (maximum absolute difference over 4,509 hardness and 9,603 yield-strength P1–P3 predictions)',
         'ys': '0.0001 MPa (maximum absolute difference over 135 folds)',
         'tabpfn': '0.001 HV or MPa'}
