def fig(path, caption, width_mm=165):
    im = Image.open(path)
    return ('figure', dict(path=path, width_mm=width_mm, aspect=im.size[1] / im.size[0], caption=caption, alt=caption[:120]))


def main(out="/home/claude/hea/manuscript/out/supplementary_information.docx"):
    R = data_stats(); X = Res()
    from text_front import TITLE
    B = [('title', 'Supplementary Information'),
         ('plain', f"for: {TITLE}", {'align': 'left', 'italic': True, 'after': 60}),
         ('plain', "Rohul Amin, Md. Mehedi Rahman Rana, Sumya Akter", {'align': 'left', 'after': 240}),
         ('h1', 'S1. Data curation details'),
         ('p', f"Records were taken from MPEA_dataset.csv of the CitrineInformatics/MPEA_dataset repository (commit "
               f"{R['mpea_commit']}; {R['mpea_records']} records) [@borg2020,mpea_github]. Hardness records were retained when "
               f"the Vickers hardness was reported and the test temperature was 25 °C or missing; {R['HV_excl_T']} records "
               f"measured at {R['HV_excl_Tmin']:.0f}–{R['HV_excl_Tmax']:.0f} °C were excluded. Yield-strength records were "
               f"retained when yield strength, test type (T or C) and test temperature were all reported. Formulas were parsed "
               f"into element amounts and normalized to atomic fractions; composition keys use fractions rounded to 0.001. "
               f"Processing classes follow the database: CAST (as-cast or directionally solidified), ANNEAL (annealed, "
               f"homogenized or aged), WROUGHT (rolled or forged), POWDER (powder metallurgy, sintering, mechanical alloying), "
               f"OTHER (additive manufacturing, HIP, severe plastic deformation) and UNKNOWN (not reported). The GE external "
               f"file (MD5 {R['ge_md5']}) was downloaded from figshare [@ge_figshare]; hardness in GPa was converted to HV "
               f"by multiplying by 1000/9.80665, and all alloys were assigned the CAST class (as-arc-melted)."),
         ('table', s_features()),
         ('table', s_hparams()),
         ('table', V.s_tabpfn(X.tabcfg)),
         ('table', V.s_selected({'HV': f"{RES}/HV_params.jsonl", 'YS': f"{RES}/YS_params.jsonl"},
                                {'HV': f"{RES}/v2/HV_params.jsonl", 'YS': f"{RES}/v2/YS_params.jsonl"})),
         ('h1', 'S2. Deployment-specific inner folds and conformal calibration'),
         ('p', "Inner folds were generated by conformal.py of the repository for every outer split, with the same seeds for "
               "tuning (three folds) and calibration (five folds). Leave-one-element-out schemes (P4, P6) take eligible elements "
               "(5–60% of the training records) in order of decreasing frequency; each inner model is trained only on records "
               "without the held-out element and is calibrated on the not-yet-assigned records that contain it, so every "
               "calibration residual is an unseen-element residual. Forward-chaining schemes (P5) calibrate each of the latest "
               "five publication years of the training literature with a model trained on all earlier years. The realised "
               "schemes (held-out elements or years, numbers of calibration records) are stored with every prediction in "
               "results/v2/*_params.jsonl. CV+ order statistics follow Barber et al. exactly, including infinite end points when "
               "the required order statistic does not exist; group-weighted quantiles give every alloy system unit total weight "
               "and the test point unit weight. The implementation reproduces nominal coverage on synthetic exchangeable data "
               "(tests in the repository)."),
         ('h1', 'S3. Complete accuracy results'),
         ('table', V.s_perf(X.perf, 'HV', 3)),
         ('table', V.s_perf(X.perf, 'YS', 4)),
         ('table', V.s_element(X.folds, 'HV', 5)),
         ('table', V.s_element(X.folds, 'YS', 6)),
         ('table', V.s_pairwise(X.pair, 7)),
         ]
    # Table S8 dedup
    dd = X.dedup_sensitivity.groupby(['data', 'n', 'protocol', 'model']).agg(RMSE=('RMSE', 'mean'), RMSE_sd=('RMSE', 'std'), R2=('R2', 'mean')).reset_index()
    rows = [[r.data, int(r.n), PNAME[r.protocol], r.model, f"{r.RMSE:.1f} ± {r.RMSE_sd:.1f}", f"{r.R2:.3f}"] for r in dd.itertuples()]
    B.append(('table', dict(caption="**Table S8.** Effect of de-duplication on hardness errors (fixed hyper-parameters; three repeats "
                                    "of five-fold cross-validation).", header=['Data', 'Records', 'Protocol', 'Model', 'RMSE (HV)', '*R*^{2}'],
                            rows=rows, widths=[1.3, 0.8, 1.3, 0.8, 1.3, 0.8],
                            notes="De-duplicated: one record (median hardness) per composition and processing route. Mean ± SD "
                                  "over the 15 folds (descriptive only).")))
    # Table S9 ablation full
    A = X.ablation_summary.copy()
    rows = []
    for ds in ('HV', 'YS'):
        for v in ['FRAC', 'PHYS', 'MAG', 'PHYS+MAG', 'ALL', 'ALL-noPROC', 'ALL+PHASE']:
            for m in ('XGB', 'GPR', 'kNN'):
                g = A[(A.ds == ds) & (A.variant == v) & (A.model == m)].set_index('protocol')
                rows.append([ds, v, m] + [f"{g.loc[p, 'RMSE']:.0f}" for p in ('random', 'composition', 'system', 'element', 'temporal')])
    B.append(('table', dict(caption="**Table S9.** Feature-block ablation for XGB, GPR and kNN (test RMSE; HV or MPa; fixed "
                                    "hyper-parameters, so independent of the inner-fold scheme).",
                            header=['Data', 'Feature set', 'Model', 'Random', 'Comp.', 'System', 'Element', 'Temporal'],
                            rows=rows, widths=[0.6, 1.4, 0.7, 0.8, 0.8, 0.8, 0.8, 0.8])))
    # Table S10 screening
    W = X.within_system_rho.groupby(['dataset', 'model']).rho.agg(['median', 'mean', 'count']).reset_index()
    K = X.topk_recall
    rows = [[r.dataset, r.model, f"{r.median:.2f}", f"{r.mean:.2f}", int(r.count)] for r in W.itertuples()]
    B.append(('table', dict(caption="**Table S10a.** Within-system Spearman correlation for held-out systems (P3, systems with ≥ 5 "
                                    "test records; yield strength restricted to room-temperature compression).",
                            header=['Data', 'Model', 'Median *ρ*', 'Mean *ρ*', 'System–repeat pairs'], rows=rows,
                            widths=[0.8, 1.0, 1.0, 1.0, 1.4])))
    Kp = K.pivot_table(index=['dataset', 'label', 'model'], columns='score', values='recall').reset_index()
    rows = [[r['dataset'], r['label'], r['model']] + [('–' if pd.isna(r.get(c)) else f"{r.get(c):.2f}") for c in ('mean', 'UCB', 'LCB')] for _, r in Kp.iterrows()]
    B.append(('table', dict(caption="**Table S10b.** Recall of the true top 20% of alloys when ranked by the point prediction, the "
                                    "upper bound (UCB) or the lower bound (LCB) of the deployment-matched 68% CV+ interval (random "
                                    "expectation 0.20).", header=['Data', 'Test set', 'Model', 'Mean', 'UCB', 'LCB'], rows=rows,
                            widths=[0.7, 1.4, 1.0, 0.8, 0.8, 0.8])))
    B.append(('table', V.s_adsens(X.ad_sensitivity_v2, 11)))
    B.append(('h1', 'S4. Uncertainty quantification'))
    B.append(('table', V.s_uq(X.uq, 12)))
    B.append(fig(f"{FIG}/Fig5_uncertainty_coverage68.png", "**Fig. S1.** As Fig. 7 but for nominal 68% intervals."))
    B.append(('h1', 'S5. External validation by subset, temporal overlap and experimental variability'))
    B.append(('table', V.s_external(X.external_subsets_v2, 13)))
    B.append(('table', V.s_external_cov(X.external_subsets_v2, 13)))
    B.append(('table', V.s_temporal(X.temporal_overlap_v2, 14)))
    B.append(('table', V.s_noise(X.noise2, 15)))
    B.append(('p', "In the yield-strength data, 36 of the 133 repeat groups (77 records) contain identical values, and 34 of these "
                   "span several publications, which indicates that some repeats are re-tabulations of one measurement rather "
                   "than independent replicates; such groups lower the pooled SD. In the hardness data, 5 of 53 groups are "
                   "identical. The pooled SD is therefore an approximate, not an exact, noise floor."))
    B.append(('h1', 'S6. Effect of the inner-validation scheme on accuracy'))
    B.append(('table', V.s_tuning(X.tuning_scheme_v2, 16)))
    B.append(('h1', 'S7. Software, computation and reproducibility'))
    B.append(('p', "Workstation: Python 3.13; scikit-learn 1.9.1; XGBoost 3.4.1; numpy 2.5; pandas 2.3; scipy 1.18; matminer "
                   "0.10.1; pymatgen 2026.10; shap 0.54. All classical models of the revision, including the yield-strength GPR, "
                   "RF and MLP runs previously executed on Kaggle, were run on the workstation and their per-record predictions "
                   "stored; refitting the tuned XGBoost models reproduced the stored predictions of the original runs to within "
                   + REPRO['xgb'] + ", and the per-fold RMSEs of the yield-strength GPR, RF and MLP runs reproduced the earlier "
                   "Kaggle runs to within " + REPRO['ys'] + ". TabPFN (tabpfn 9.2.0, Table S2b) was run twice on an NVIDIA T4 "
                   "GPU in Kaggle notebooks with the same seeds; the second run, which also produced the per-record predictions "
                   "used for the cluster bootstrap and the deployment-matched CV+ intervals for P4–P6, reproduced the per-fold "
                   "RMSEs of the first run to within " + REPRO['tabpfn'] + "."))
    B.append(('references',))
    build(B, {'creator': 'Rohul Amin', 'title': 'Supplementary Information', 'description': 'SI'},
          out.replace('.docx', '.json'), out)


if __name__ == '__main__':
    main()
